#!/usr/bin/env python3
"""Assemble the supplementary release: every prompt as text, every setting as JSON.

    python results/utils/build_supplementary.py

Both artefacts are DERIVED, never transcribed. The prompts are copied from prompt/ and
the settings are imported from eval/llm/run_openai.py and run_ollama.py, so the release
cannot drift from the code that produced the results. Re-run after any change to either.

LAYOUT. Prompts are reorganised by dataset rather than kept in the pipeline's
group/protocol tree, because the question a reader asks is "show me the nine conditions
for this corpus", not "show me every dataset's CoT prompt".

    supplementary/prompts/<dataset>/<group>__<protocol>.txt

Placeholders in braces are filled per instance at generation time: {sentence}, {text},
{term1}/{term2}, {token}/{index}, {question}/{options}/{letters}, {polarity} for the
sentiment True/False recast, and {suggestion} for the QUIZ confirmation-bias plant.
Image datasets carry the image itself rather than a text placeholder.
"""
import json
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "eval"))
sys.path.insert(0, str(ROOT / "eval" / "llm"))
import run_openai as O                                               # noqa: E402
import run_ollama as L                                               # noqa: E402

OUT = ROOT / "supplementary"
GROUPS = ["basic_instruction", "control", "customized"]
PROTOCOLS = ["vanilla", "cot", "topk"]
DATASETS = ["sentiment", "movie_reviews", "crowdtruth", "conll_ner",
            "pico", "quiz", "labelme", "imagenet16h"]
OFFICIAL = {"sentiment": "Sentiment Polarity", "movie_reviews": "MovieReviews",
            "crowdtruth": "CrowdTruth RelEx", "conll_ner": "CoNLL-NER",
            "pico": "PICO", "quiz": "QUIZ", "labelme": "LabelMe",
            "imagenet16h": "ImageNet-16H"}
OPEN_WEIGHT = {"llama3.1-8b-instruct-q8_0": ("llama3.1:8b-instruct-q8_0", "Llama3.1-8B"),
               "qwen2.5-7b-instruct-q8_0": ("qwen2.5:7b-instruct-q8_0", "Qwen2.5-7B"),
               "minicpm-v-8b-2.6-q8_0": ("minicpm-v:8b-2.6-q8_0", "MiniCPM-V-8B"),
               "qwen2.5vl-7b-q8_0": ("qwen2.5vl:7b-q8_0", "Qwen2.5VL-7B")}


def copy_prompts():
    n = 0
    for ds in DATASETS:
        d = OUT / "prompts" / ds
        d.mkdir(parents=True, exist_ok=True)
        for g in GROUPS:
            stem = O.TEMPLATE[g][ds]
            for p in PROTOCOLS:
                src = ROOT / "prompt" / g / p / f"{stem}.txt"
                if not src.exists():
                    print(f"  MISSING {src.relative_to(ROOT)}")
                    continue
                shutil.copyfile(src, d / f"{g}__{p}.txt")
                n += 1
    return n


def settings():
    return {
        "_note": ("Generated by results/utils/build_supplementary.py directly from "
                  "eval/llm/run_openai.py and eval/llm/run_ollama.py. Do not edit by "
                  "hand; re-run the script instead."),
        "decoding": {
            "temperature": O.TEMPERATURE,
            "top_p": O.TOP_P,
            "seed": O.SEED,
            "samples_per_query": 1,
            "_comment": ("Identical for every model, dataset and prompting condition. "
                         "Greedy decoding under a fixed seed makes variation across "
                         "the nine conditions attributable to the prompt rather than "
                         "to sampling."),
        },
        "closed_source": {
            "display_name": "GPT-4o-mini",
            "model": O.MODEL,
            "endpoint": "OpenAI Chat Completions",
            "response_format": {"type": "json_object"},
            "_comment": ("Pinned to a dated snapshot rather than the moving alias, so "
                         "the run is reproducible against a fixed backend."),
        },
        "open_weight": {
            "server": "Ollama",
            "num_ctx": L.NUM_CTX,
            "top_k": 0,
            "repeat_penalty": 1.0,
            "format": "json",
            "quantisation": "q8_0",
            "models": [{"display_name": disp, "ollama_tag": tag, "output_dir": safe}
                       for safe, (tag, disp) in OPEN_WEIGHT.items()],
            "_comment": ("num_ctx is set explicitly because Ollama's default silently "
                         "truncates an over-long prompt. It bounds the context for the "
                         "open-weight models regardless of the checkpoint's own limit."),
        },
        "max_output_tokens": {
            "_comment": ("Per dataset and protocol, uniform across the three prompt "
                         "groups, sized to roughly five times the measured 99th "
                         "percentile of generation length. Truncation is silent and "
                         "clips the longest generations first, which would bias the "
                         "surviving sample toward shorter and easier instances."),
            "default": O.MAX_TOKENS,
            "overrides_by_group": {"customized": O.MAX_TOKENS_CUSTOM},
        },
        "prompting_conditions": {
            "groups": GROUPS,
            "protocols": PROTOCOLS,
            "conditions_per_instance": 9,
            "manipulation_by_dataset": {
                OFFICIAL[ds]: O.TEMPLATE["customized"][ds] for ds in DATASETS},
            "_comment": ("Three prompt groups crossed with three elicitation protocols. "
                         "Sentiment Polarity realises twelve conditions rather than "
                         "nine: its True/False recast queries each sentence twice, "
                         "counterbalanced over the asserted polarity."),
        },
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    n = copy_prompts()
    (OUT / "model_settings.json").write_text(
        json.dumps(settings(), indent=2, ensure_ascii=False) + "\n")
    print(f"  prompts/            {n} files across {len(DATASETS)} datasets")
    print(f"  model_settings.json {len((OUT / 'model_settings.json').read_text())} bytes")


if __name__ == "__main__":
    main()
